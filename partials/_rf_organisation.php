        <h3 class="rf-subtitle">Gestion du projet via Teams</h3>
        <div class="rf-content">
            <p>
                L'organisation du projet s'est appuyée sur plusieurs outils complémentaires, chacun ayant un rôle précis
                dans la gestion du travail, de la communication et de la production des livrables.
                Microsoft Teams a constitué l'outil central de communication et de coordination. Un espace dédié a été
                mis en place, regroupant l'ensemble du groupe ainsi que les enseignants encadrants, et structuré en
                plusieurs canaux distincts.</p>

            <div class="rf-pages-grid">
                <div class="rf-page-item" id="whitas">
                    <span class="rf-page-icon">💬</span>
                    <div>
                        <strong>Canal « Général »</strong>
                        <p>Espace d'échanges quotidiens et de questions rapides entre les membres du groupe.</p>
                    </div>
                </div>
                <div class="rf-page-item" id="whitas">
                    <span class="rf-page-icon">📅</span>
                    <div>
                        <strong>Canal « Réunion »</strong>
                        <p>Utilisé pour annoncer les prochaines séances de travail et organiser le planning de l'équipe.</p>
                    </div>
                </div>
                <div class="rf-page-item" id="whitas">
                    <span class="rf-page-icon">📁</span>
                    <div>
                        <strong>Canal « Important »</strong>
                        <p>Centralisation de tous les documents essentiels du projet, accessibles à l'ensemble des membres à tout moment.</p>
                    </div>
                </div>
                <div class="rf-page-item" id="whitas">
                    <span class="rf-page-icon">📝</span>
                    <div>
                        <strong>Canal « Compte-rendu »</strong>
                        <p>Suivi précis des réunions pour les présents comme pour les absents. Après chaque séance, un membre rédigeait à tour de rôle un compte-rendu précisant les participants, la durée, les points abordés.</p>
                    </div>
                </div>
            </div>

            <p>
                La gestion des tâches s'intégrait naturellement à cet environnement. En fin de réunion, le chef de
                groupe, Alan, définissait les missions à réaliser, aussi bien à l'oral qu'à l'écrit, en précisant les
                échéances et les personnes responsables. Ce planning, organisé par rôles, permettait à chacun de savoir
                précisément ce qu'il avait à accomplir et de s'y référer facilement en cas de besoin.
                Pour assurer un suivi visuel et structuré de ces tâches, le groupe a utilisé le
                <strong>Planificateur</strong> intégré à Microsoft Teams. Cet outil, fonctionnant selon le principe du
                <strong>Kanban</strong>, permettait de représenter l'avancement du projet sous forme de tableau organisé
                en colonnes. Chaque tâche y était créée, assignée à un ou plusieurs membres, puis déplacée au fil de son
                avancement. Ce système offrait ainsi une vision claire et partagée à tout moment : savoir ce qui restait
                à faire, où en était chaque tâche en cours, et qui en était responsable. Cela réduisait les risques
                d'oubli et facilitait la coordination entre les membres, notamment entre deux réunions.
            </p>

            <img src="../assets/images/planiteams.png" alt="Images" style="width: 100%; padding-bottom: 20px">

            <p>
                Le projet s'est articulé autour de réunions régulières, généralement tenues deux fois par semaine,
                toujours aux alentours de 14h. La première, en début de semaine, avait pour objectif de définir le
                déroulement de la semaine et de répartir les tâches entre les membres. La seconde, placée en fin de
                semaine ( le jeudi ou le vendredi selon les besoins ) visait à faire un point sur l'avancement des
                tâches réalisées, à identifier les éventuels problèmes rencontrés et à traiter les merges ainsi que les
                conflits de fusion du code. Contrairement au développement classique, où l'on évite généralement toute
                mise en production en fin de semaine, le vendredi représentait ici l'une de nos journées les plus
                importantes. Ce fonctionnement offrait par ailleurs une certaine flexibilité : en cas de besoin, une
                réunion supplémentaire pouvait être organisée afin de disposer du temps nécessaire à la bonne
                réalisation de chaque tâche. En fin de projet, la fréquence des réunions a également augmenté pour
                répondre à la charge de travail plus importante liée à la finalisation des livrables et à la préparation
                de la soutenance orale.
            </p>

