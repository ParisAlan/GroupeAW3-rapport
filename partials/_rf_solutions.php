            <!-- V1 -->
            <div class="rf-solution-card">
                <div class="rf-solution-badge">V1</div>
                <h3 class="rf-solution-subtitle">Solution V1</h3>
                <p>La version V1 de <em>MyGreen Campus</em> constitue une première réponse fonctionnelle à la problématique identifiée. Elle présente l'avantage d'être simple, accessible et réalisable dans le temps imparti, tout en proposant une première expérience utilisateur.</p>
                <div class="rf-critique">
                    <h4 class="rf-critique-title">⚠️ Limites identifiées</h4>
                    <ul class="rf-list">
                        <li>Le calcul de l'empreinte carbone repose sur un algorithme simplifié. Des API spécialisées n'ont pas été intégrées, ce qui peut entraîner une précision limitée des résultats.</li>
                        <li>La gamification reste partiellement aboutie : l'interface propose des badges et des défis écologiques, mais le système de validation par l'utilisateur ainsi que le calcul des points associés ne sont pas encore pleinement fonctionnels.</li>
                        <li>Les recommandations proposées restent relativement génériques et ne prennent pas suffisamment en compte les spécificités de chaque utilisateur.</li>
                        <li>La dimension technique reste volontairement simple afin de garantir la faisabilité du projet, mais cela limite les possibilités d'évolution et d'amélioration de la plateforme.</li>
                        <li>Certains éléments visuels pourraient être davantage travaillés pour optimiser l'expérience utilisateur.</li>
                    </ul>
                </div>
                <p class="rf-conclusion">Ainsi, la V1 constitue une base solide, mais nécessite des améliorations pour devenir une solution plus complète, plus engageante et mieux adaptée aux besoins des étudiants.</p>
            </div>

            <!-- V2 -->
            <div class="rf-solution-card">
                <div class="rf-solution-badge rf-solution-badge--v2">V2</div>
                <h3 class="rf-solution-subtitle">Solution V2 (cahier des charges)</h3>
                <p>La solution proposée à travers le cahier des charges V2 de MyGreen Campus présente plusieurs points forts, mais également certaines limites qu'il convient d'identifier.</p>
                <div class="rf-critique">
                    <h4 class="rf-critique-title">⚠️ Limites identifiées</h4>
                    <ul class="rf-list">
                        <li>La complexité technique est significativement renforcée (MongoDB, gamification avancée, défis collaboratifs, partenaires, multilingue), impliquant un développement plus long et plus exigeant.</li>
                        <li>Certaines fonctionnalités reposent sur des éléments difficilement maîtrisables : partenariats locaux, défis collectifs, dépendants de l'implication d'acteurs externes.</li>
                        <li>Bien que la plateforme mise sur la gamification, la fidélisation des utilisateurs sur le long terme reste incertaine. Les mécanismes proposés nécessitent un renouvellement constant.</li>
                        <li>La fiabilité des résultats reste une limite : les estimations d'empreinte carbone reposent sur des données simplifiées et des moyennes.</li>
                        <li>L'ambition du projet (ouverture internationale, modèle économique) peut apparaître difficile à concrétiser à court terme.</li>
                    </ul>
                </div>
            </div>
