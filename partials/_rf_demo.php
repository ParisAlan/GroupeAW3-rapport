            <h3 class="rf-subtitle">Conception et Architecture</h3>

            <p>
                Le projet repose sur une architecture respectant le modèle MVC (Modèle-Vue-Contrôleur), conformément aux
                bonnes pratiques du framework Symfony.
                L’organisation du code s’articule ainsi autour de contrôleurs gérant la logique applicative, d’entités
                représentant les données métiers et leur persistance en base, ainsi que de vues assurant le rendu côté
                utilisateur.
                Cette structuration claire permet de garantir la maintenabilité, la modularité et l’évolutivité de
                l’application.
            </p>

            <p>
                L'une de nos premières démarches a été de concevoir un diagramme de classes pour mieux cerner
                la structure globale du projet avant d'entamer le développement. Cette étape nous a semblé
                indispensable pour partir sur des bases solides, tout en sachant que ce modèle resterait évolutif
                et s'adapterait aux besoins qui émergeraient au fil du temps. Un diagramme de classes détaillant
